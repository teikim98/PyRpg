CH = {}
for _i, (_name, _hex) in enumerate(COLORS.items()):
    _c = _POOL[_i]
    if _c in PALETTE:
        raise ValueError(f"palette char clash: {_c!r}")
    PALETTE[_c] = _rgba(_hex)
    CH[_name] = _c
NAME = {c: n for n, c in CH.items()}
