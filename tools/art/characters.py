"""캐릭터 시트.

새 형식(그래픽 개편, docs/art-overhaul/style-guide.md §5~6): 16×24 프레임, 6열 × 4행 = 24프레임.
행 = 아래·왼쪽·오른쪽·위, 열 = 서기·왼발·서기·오른발·숨쉬기·눈 깜빡임. charrig.Rig가 머리·몸통 그리드에
코드로 그리는 팔·다리를 합성하고, 코지 팔레트(cozypal)로 칠한 뒤 바깥 외곽선을 두른다.
지금 새 형식인 캐릭터: 주인공(player), 누리(nuri), 지역 1 NPC(npc_merchant, npc_villager, npc_child).

옛 형식(16×16 프레임 8개: 아래×2, 왼쪽×2, 오른쪽×2, 위×2): 지역 2~6 NPC 모듈이 아래 character()로 만든다.
확장 단계에서 새 형식으로 옮긴다.
"""
