from charrig import Rig, mirror, rows
from cozypal import auto_outline, c

# 열 번호 안내: 0123456789abcdef

GHOST_LEGEND = {
    "s": "sky.spec", "S": "white", "z": "sky.hi", "p": "blush", "e": "eye",                 # 푸르스름한 얼굴
    "a": "cloth_white.base", "A": "cloth_white.hi", "q": "cloth_white.shade",              # 하얗게 센 올림머리
    "Q": "teal.hi",                                                                        # 렌즈 반사
    "t": "sky.base", "T": "sky.hi", "y": "sky.shade",                                      # 로브
    "c": "cream.base", "C": "cream.hi", "x": "cream.shade",                                # 양피지색 숄
    "r": "brass.base", "R": "brass.hi", "u": "brass.shade",                                # 안경테
    "g": "brick.base", "G": "brick.hi", "k": "brick.shade",                                # 안은 책
    "v": "sky.shade", "f": "foam",                                                         # 로브 꼬리, 흐려지는 끝 올
}


def _tail_row(x0, x1, off, keep):
    """x0..x1 칸 중 (x + off) % 3이 keep에 드는 칸만 남긴 한 줄(로브 자락의 물결)."""
    return "".join(("v" if keep == "v" else "f") if x0 <= x <= x1 and (x + off) % 3 in
                   ((0, 1) if keep == "v" else (0,)) else "." for x in range(16))


def ghost_tail(direction, pose):
    """다리 대신 19~22행: 로브 자락이 퍼졌다가 물결 모양 끝(그늘)과 반투명 끝 올로 흐려진다.
    발 딛는 프레임(stepA·stepB)마다 물결이 한 칸씩 옮겨 가서 떠서 미끄러지는 것처럼 보인다."""
    off = {"stand": 0, "stepA": 1, "stepB": 2}[pose]
    if direction in ("down", "up"):
        g = rows("""
            ....tTttttty....
            ...tTttttttty...
        """) + [_tail_row(3, 12, off, "v"), _tail_row(4, 11, off, "f")]
        return g
    g = rows("""
        .....tTtttty....
        ....tTtttty.....
    """) + [_tail_row(3, 9, off, "v"), _tail_row(2, 7, off, "f")]
    return mirror(g) if direction == "left" else g


class GhostRig(Rig):
    """반투명 끝 올(foam)에는 외곽선을 두르지 않는다(나머지는 Rig와 같음)."""

    def frames(self):
        table = {".": "."}
        for k, v in self.legend.items():
            table[k] = c(v)
        return [auto_outline(["".join(table[ch] for ch in r) for r in g], skip={c("foam")})
                for g in self.letter_frames()]


