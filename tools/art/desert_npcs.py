# 지팡이 자리(방향 → 열, 굽은 끝이 향하는 쪽). 왼쪽은 오른쪽의 거울
_STAFF = {"down": (13, -1), "right": (14, -1), "left": (1, 1), "up": (2, 1)}


def _guide_staff(direction, col, g):
    """지팡이: 1행(걸을 때 2행)에서 22행(땅)까지 세로 막대, 꼭대기는 안쪽으로 굽은 손잡이."""
    x, hook = _STAFF[direction]
    top = 1 + (1 if col in (1, 3) else 0)
    put(g, x, top, "Q")
    put(g, x + hook, top, "Q")
    put(g, x + hook, top + 1, "o")
    for y in range(top + 1, 23):
        put(g, x, y, "m" if y % 5 else "o")
    return g


